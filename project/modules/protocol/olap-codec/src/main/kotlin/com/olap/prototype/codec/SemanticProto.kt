/** 正式语义类型与具体生成消息的显式边界；不注册任意对象或猜测类型。 */
object SemanticProto {
    fun toProto(value: Q.Members) = SemanticQueryProto.members(value)
    fun fromProto(value: QueryMembers) = SemanticQueryProto.members(value)
    fun toProto(value: com.olap.prototype.query.QueryComputation.TimeRange) = SemanticQueryProto.timeRange(value)
    fun fromProto(value: com.olap.prototype.wire.semantic.QueryTimeRange) = SemanticQueryProto.timeRange(value)
    fun toProto(v: com.olap.prototype.connector.ConnectorRef): ConnectorRef = ConnectorRef.newBuilder().setId(v.id).setVersion(v.version).setSha256(v.sha256).build()
    fun fromProto(v: ConnectorRef): com.olap.prototype.connector.ConnectorRef = com.olap.prototype.connector.ConnectorRef(v.id, v.version, v.sha256)
    fun toProto(v: com.olap.prototype.calculation.MetricRef): MetricRef = MetricRef.newBuilder().setId(v.id).setVersion(v.version).build()
    fun fromProto(v: MetricRef): com.olap.prototype.calculation.MetricRef = com.olap.prototype.calculation.MetricRef(v.id, v.version)
    fun toProto(v: com.olap.prototype.calculation.MetricInstanceRef): MetricInstanceRef = MetricInstanceRef.newBuilder().setId(v.id).build()
    fun fromProto(v: MetricInstanceRef): com.olap.prototype.calculation.MetricInstanceRef = com.olap.prototype.calculation.MetricInstanceRef(v.id)
    fun toProto(v: com.olap.prototype.member.MemberRef): MemberRef = MemberRef.newBuilder().setId(v.id).setVersion(v.version).build()
    fun fromProto(v: MemberRef): com.olap.prototype.member.MemberRef = com.olap.prototype.member.MemberRef(v.id, v.version)
    fun toProto(v: com.olap.prototype.event.EventRef): EventRef = EventRef.newBuilder().setEventId(v.eventId).setEventVersion(v.eventVersion).build()
    fun fromProto(v: EventRef): com.olap.prototype.event.EventRef = com.olap.prototype.event.EventRef(v.eventId, v.eventVersion)
    fun toProto(v: ScopedInputContract.DimensionRef) = SemanticTypesProto.dimension(v)
    fun fromProto(v: DimensionRef) = SemanticTypesProto.dimension(v)
    fun toProto(v: com.olap.prototype.event.RelationAccessPath) = SemanticTypesProto.path(v)
    fun fromProto(v: RelationAccessPath) = SemanticTypesProto.path(v)
    fun toProto(v: com.olap.prototype.event.RelationAccessPath.JoinRef): JoinRef = JoinRef.newBuilder().setJoinPathId(v.joinPathId).setJoinPathVersion(v.joinPathVersion).build()
    fun fromProto(v: JoinRef): com.olap.prototype.event.RelationAccessPath.JoinRef = com.olap.prototype.event.RelationAccessPath.JoinRef(v.joinPathId, v.joinPathVersion)
    fun toProto(v: com.olap.prototype.event.EventIdentity) = SemanticTypesProto.identity(v)
    fun fromProto(v: EventIdentity) = SemanticTypesProto.identity(v)
    fun toProto(v: com.olap.prototype.time.TemporalWindow) = SemanticTypesProto.window(v)
    fun fromProto(v: TemporalWindow) = SemanticTypesProto.window(v)
    fun toProto(v: TemporalClockBindings.Value) = SemanticTypesProto.clock(v)
    fun fromProto(v: TemporalClock) = SemanticTypesProto.clock(v)
    fun toProto(v: TemporalJoinContract.Constraint) = SemanticTypesProto.temporal(v)
    fun fromProto(v: TemporalConstraint) = SemanticTypesProto.temporal(v)
    fun toProto(v: E) = SemanticExpressionsProto.expression(v)
    fun fromProto(v: SemanticExpression) = SemanticExpressionsProto.expression(v)
    fun toProto(v: RE) = SemanticExpressionsProto.result(v)
    fun fromProto(v: ResultExpression) = SemanticExpressionsProto.result(v)
    fun toProto(v: V) = SemanticTypesProto.value(v)
    fun fromProto(v: MetricValueContract) = SemanticTypesProto.value(v)
    fun toProto(v: V.UnitIdentity) = SemanticTypesProto.unitIdentity(v)
    fun fromProto(v: UnitIdentity) = SemanticTypesProto.unitIdentity(v)
    fun toProto(v: BM) = SemanticTypesProto.meaning(v)
    fun fromProto(v: MetricBusinessMeaning) = SemanticTypesProto.meaning(v)
    fun toProto(v: SO.Shape) = SemanticTypesProto.shape(v)
    fun fromProto(v: SetOutputShape) = SemanticTypesProto.shape(v)
    fun toProto(v: SO) = SemanticTypesProto.output(v)
    fun fromProto(v: SetOutput) = SemanticTypesProto.output(v)
    fun toProto(v: C.Binding) = SemanticCalculationProto.binding(v)
    fun fromProto(v: CalculationBinding) = SemanticCalculationProto.binding(v)
    fun toProto(v: C.Scalar) = SemanticCalculationProto.scalar(v)
    fun fromProto(v: CalculationScalar) = SemanticCalculationProto.scalar(v)
    fun toProto(v: C) = SemanticCalculationProto.calculation(v)
    fun fromProto(v: Calculation) = SemanticCalculationProto.calculation(v)
    fun toProto(v: C.Scope) = SemanticCalculationProto.scope(v)
    fun fromProto(v: CalculationScope) = SemanticCalculationProto.scope(v)
    fun toProto(v: C.ObservationUnit) = SemanticCalculationProto.observation(v)
    fun fromProto(v: ObservationUnit) = SemanticCalculationProto.observation(v)
    fun toProto(v: B) = SemanticCalculationProto.bindings(v)
    fun fromProto(v: CalculationBindings) = SemanticCalculationProto.bindings(v)
    fun toProto(v: B.Dimension) = SemanticCalculationProto.dimension(v)
    fun fromProto(v: DimensionBinding) = SemanticCalculationProto.dimension(v)
    fun toProto(v: B.Member) = SemanticCalculationProto.member(v)
    fun fromProto(v: MemberBinding) = SemanticCalculationProto.member(v)
    fun toProto(v: B.Relation) = SemanticCalculationProto.relation(v)
    fun fromProto(v: RelationBinding) = SemanticCalculationProto.relation(v)
    fun toProto(v: DC) = SemanticCalculationProto.condition(v)
    fun fromProto(v: DimensionCondition) = SemanticCalculationProto.condition(v)
    fun toProto(v: MD) = SemanticCalculationProto.memberCondition(v)
    fun fromProto(v: MemberCondition) = SemanticCalculationProto.memberCondition(v)
    fun toProto(v: Q.Scope) = SemanticQueryProto.scope(v)
    fun fromProto(v: QueryScope) = SemanticQueryProto.scope(v)
    fun toProto(v: PO.ValidatedOperation) = SemanticStagesProto.stage(v)
    fun fromProto(v: Stage) = SemanticStagesProto.stage(v)
    fun toProto(v: PO.ResultAggregate) = SemanticStagesProto.aggregate(v)
    fun fromProto(v: ResultAggregate) = SemanticStagesProto.aggregate(v)
    fun toProto(v: RA) = SemanticStagesProto.aggregation(v)
    fun fromProto(v: ResultAggregation) = SemanticStagesProto.aggregation(v)
    fun toProto(v: M) = SemanticDefinitionsProto.metric(v)
    fun fromProto(v: MetricDefinition) = SemanticDefinitionsProto.metric(v)
    fun toProto(v: MC) = SemanticDefinitionsProto.calculation(v)
    fun fromProto(v: MetricCalculation) = SemanticDefinitionsProto.calculation(v)
    fun toProto(v: MI) = SemanticDefinitionsProto.instance(v)
    fun fromProto(v: MetricInstance) = SemanticDefinitionsProto.instance(v)
    fun toProto(v: SR) = SemanticDefinitionsProto.snapshot(v)
    fun fromProto(v: MetricSnapshotRule) = SemanticDefinitionsProto.snapshot(v)
    fun toProto(v: MSD) = SemanticDefinitionsProto.memberDefinition(v)
    fun fromProto(v: MemberSourceDefinition) = SemanticDefinitionsProto.memberDefinition(v)
    fun toProto(v: MS) = SemanticDefinitionsProto.member(v)
    fun fromProto(v: MemberSource) = SemanticDefinitionsProto.member(v)
    fun toProto(v: com.olap.prototype.query.QueryValue) = SemanticValuesProto.value(v)
    fun fromProto(v: QueryValue) = SemanticValuesProto.value(v)
    fun toProto(v: com.olap.prototype.query.QueryQuantity) = SemanticValuesProto.quantity(v)
    fun fromProto(v: QueryQuantity) = SemanticValuesProto.quantity(v)
    fun toProto(v: com.olap.prototype.query.QueryStageAnalysis.Symbol) = SemanticValuesProto.symbol(v)
    fun fromProto(v: Symbol) = SemanticValuesProto.symbol(v)
    fun toProto(v: com.olap.prototype.query.QueryStageAnalysis.SymbolId) = SemanticValuesProto.id(v)
    fun fromProto(v: SymbolId) = SemanticValuesProto.id(v)
    fun toProto(v: com.olap.prototype.query.QueryStageAnalysis.ScopeId) = SemanticValuesProto.scope(v)
    fun fromProto(v: ScopeId) = SemanticValuesProto.scope(v)
    fun toProto(v: com.olap.prototype.query.QueryStageAnalysis.SelectedObservation) = SemanticValuesProto.observation(v)
    fun fromProto(v: SelectedObservation) = SemanticValuesProto.observation(v)
    fun toProto(v: com.olap.prototype.query.QueryStageAnalysis.MemberMeaning) = SemanticValuesProto.meaning(v)
    fun fromProto(v: MemberMeaning) = SemanticValuesProto.meaning(v)
    fun toProto(v: com.olap.prototype.calculation.CalculationOwner) = SemanticValuesProto.owner(v)
    fun fromProto(v: CalculationOwner) = SemanticValuesProto.owner(v)
    fun toProto(v: C.ObjectTarget) = SemanticCalculationProto.objectTarget(v)
    fun fromProto(v: ObjectTarget) = SemanticCalculationProto.objectTarget(v)
    fun toProto(v: C.ObjectRole) = SemanticCalculationProto.objectRole(v)
    fun fromProto(v: ObjectRole) = SemanticCalculationProto.objectRole(v)
    fun toProto(v: C.SetProjection) = SemanticCalculationProto.projection(v)
    fun fromProto(v: SetProjection) = SemanticCalculationProto.projection(v)
    fun toProto(v: C.AlignmentPopulation) = SemanticCalculationProto.alignmentPopulation(v)
    fun fromProto(v: AlignmentPopulation) = SemanticCalculationProto.alignmentPopulation(v)
    fun toProto(v: com.olap.prototype.query.RowPopulationContract.Selection) = SemanticQueryProto.population(v)
    fun fromProto(v: RowPopulation) = SemanticQueryProto.population(v)
    fun arguments(v: Map<String, C.Value>): CalculationArguments = CalculationArguments.newBuilder().putAllValues(v.mapValues { SemanticCalculationProto.binding(it.value) }).build()
    fun arguments(v: CalculationArguments): Map<String, C.Value> = v.valuesMap.mapValues { SemanticCalculationProto.value(it.value) }
    fun toProto(v: C.Parameter) = SemanticCalculationProto.parameter(v)
    fun fromProto(v: CalculationParameter) = SemanticCalculationProto.parameter(v)
    fun toProto(v: C.DimensionSlot) = SemanticCalculationProto.slot(v)
    fun fromProto(v: DimensionSlot) = SemanticCalculationProto.slot(v)
    fun toProto(v: C.MemberSlot) = SemanticCalculationProto.memberSlot(v)
    fun fromProto(v: MemberSlot) = SemanticCalculationProto.memberSlot(v)
    fun toProto(v: C.MemberOutput) = SemanticCalculationProto.output(v)
    fun fromProto(v: MemberOutput) = SemanticCalculationProto.output(v)
    fun toProto(v: C.RelationSlot) = SemanticCalculationProto.relationSlot(v)
    fun fromProto(v: RelationSlot) = SemanticCalculationProto.relationSlot(v)
    fun toProto(v: E.RelationParent) = SemanticExpressionsProto.parent(v)
    fun fromProto(v: RelationParent) = SemanticExpressionsProto.parent(v)
    fun toProto(v: V.Arithmetic) = SemanticTypesProto.arithmetic(v)
    fun fromProto(v: Arithmetic) = SemanticTypesProto.arithmetic(v)
}
